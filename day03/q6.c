#include <stdio.h>

int main() {
    int num1, num2, temp;

    // Input two numbers separated by a space
    scanf("%d %d", &num1, &num2);

    // Swap the numbers using the third variable (temp)
    temp = num1;
    num1 = num2;
    num2 = temp;

    // Display the swapped numbers exactly as shown in the test cases
    printf("After swap: %d %d\n", num1, num2);

    return 0;
}
